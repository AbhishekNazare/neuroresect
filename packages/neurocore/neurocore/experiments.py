"""Actual patient-separated synthetic benchmarks and bootstrap model refits.

Synthetic labels are generated by a declared simulator. Reported metrics measure
this software demonstration, not clinical utility. No approved patient data is
bundled and imported clinical connectomes are never sent to the demo predictor.
"""

